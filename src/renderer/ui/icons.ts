/** The icon set the app uses (lucide, built as real SVG nodes: no innerHTML, CSP-safe). */
const ICONS = {
  back: ArrowLeft,
  cash: Banknote,
  reports: ChartColumn,
  check: Check,
  up: ChevronUp,
  takeaway: ShoppingBag,
  delivery: Truck,
  down: ChevronDown,
  halls: DoorOpen,
  show: Eye,
  hide: EyeOff,
  printer: Printer,
  receipt: ReceiptText,
  system: SunMoon,
  sliders: SlidersHorizontal,
  sessions: ClipboardList,
  card: CreditCard,
  noImage: ImageOff,
  language: Languages,
  logout: LogOut,
  lock: Lock,
  hamburger: Menu,
  tables: LayoutGrid,
  minus: Minus,
  edit: Pencil,
  dark: Moon,
  plus: Plus,
  checks: Receipt,
  search: Search,
  settings: Settings,
  click: Smartphone,
  light: Sun,
  timer: Timer,
  trash: Trash2,
  warning: TriangleAlert,
  menu: UtensilsCrossed,
  users: Users,
  debt: Wallet,
  close: X,
} satisfies Record<string, IconNode>;

export type IconName = keyof typeof ICONS;

export function icon(name: IconName, size = 20): SVGElement {
  const el = createElement(ICONS[name]) as SVGElement;
  el.setAttribute('width', String(size));
  el.setAttribute('height', String(size));
  el.setAttribute('aria-hidden', 'true');
  el.setAttribute('focusable', 'false');
  el.classList.add('icon');
  return el;
}
